"""
Multi-Agent Document Research & Analytics System
=================================================
A state-of-the-art Multi-Agent system built with Python 3.10+, LangGraph 0.2+,
ChatGroq (llama3-70b/llama-3.3-70b), Supabase pgvector (RAG), HuggingFace Embeddings,
and Tavily Web Search fallback.

Architecture Flow:
Input Topic -> Orchestrator Node -> Retrieval Agent Node (Supabase pgvector)
             -> [Conditional Edge: Context Density Evaluation]
                  ├─► Sparse/Insufficient -> Web Search Fallback Node (Tavily) -> Synthesis Agent
                  └─► Sufficient          ----------------------------------------> Synthesis Agent
             -> Output: Executive Markdown Report
"""

