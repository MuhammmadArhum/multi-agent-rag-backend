# 7. WORKFLOW GRAPH BUILDER
# ============================================================================
def build_research_graph(
    groq_api_key: str = "",
    tavily_api_key: str = "",
    supabase_url: str = "",
    supabase_service_key: str = "",
    doc_threshold: int = 2,
) -> StateGraph:
    """
    Constructs and compiles the multi-agent state graph using LangGraph.
    API keys are passed as parameters and wired into node closures so that
    each request uses the correct credentials without a global state race condition.
    """
    # Resolve keys: prefer passed args, fall back to env vars
    _groq_key       = groq_api_key       or os.getenv("GROQ_API_KEY", "")
    _tavily_key      = tavily_api_key      or os.getenv("TAVILY_API_KEY", "")
    _supabase_url    = supabase_url        or os.getenv("SUPABASE_URL", "")
    _supabase_svckey = supabase_service_key or os.getenv("SUPABASE_SERVICE_KEY", "")
    _threshold       = doc_threshold

    # ── Node closures that capture resolved keys ───────────────────────────────
    def _orchestrator_node(state: ResearchState) -> Dict[str, Any]:
        topic = state["topic"]
        print(f"\n[Orchestrator Node] Processing Topic: '{topic}'")
        llm = get_groq_llm(groq_api_key=_groq_key, temperature=0.3)
        if llm:
            try:
                structured_llm = llm.with_structured_output(SubQueryOutput)
                prompt = ChatPromptTemplate.from_messages([
                    ("system", "You are an expert Principal AI Research Lead. "
                               "Break down the user's research topic into 3 to 5 highly specific, "
                               "technical sub-queries optimized for semantic document retrieval."),
                    ("human", "Research Topic: {topic}")
                ])
                formatted_prompt = prompt.format_messages(topic=topic)
                response: SubQueryOutput = structured_llm.invoke(formatted_prompt)
                queries = response.queries
            except Exception as e:
                print(f"[Orchestrator Node] Groq LLM invocation failed ({e}). Falling back to rule-based queries.")
                queries = [
                    f"{topic} core architecture and technical specifications",
                    f"{topic} implementation details and key components",
                    f"{topic} performance, benchmarks, and comparative analysis"
                ]
        else:
            print("[Orchestrator Node] No Groq API Key found. Using default sub-queries.")
            queries = [
                f"{topic} core architecture and technical specifications",
                f"{topic} implementation details and key components",
                f"{topic} performance, benchmarks, and comparative analysis"
            ]
        print(f"[Orchestrator Node] Generated Sub-Queries:\n  - " + "\n  - ".join(queries))
        return {"search_queries": queries}

    def _retrieval_node(state: ResearchState) -> Dict[str, Any]:
        queries = state.get("search_queries", [state["topic"]])
        print(f"\n[Retrieval Agent Node] Querying Supabase pgvector with {len(queries)} sub-queries...")
        vector_store = get_supabase_vectorstore(
            supabase_url=_supabase_url,
            supabase_service_key=_supabase_svckey,
        )
        retrieved_docs: List[Document] = []
        seen_contents = set()
        if vector_store:
            try:
                for query in queries:
                    docs = vector_store.similarity_search(query, k=2)
                    for doc in docs:
                        if doc.page_content not in seen_contents:
                            seen_contents.add(doc.page_content)
                            retrieved_docs.append(doc)
                print(f"[Retrieval Agent Node] Retrieved {len(retrieved_docs)} unique documents.")
            except Exception as e:
                print(f"[Retrieval Agent Node] Supabase RAG query error: {e}")
        else:
            print("[Retrieval Agent Node] Supabase not configured. Operating in local mode.")
        need_web_search = len(retrieved_docs) < _threshold
        if need_web_search:
            print(f"[Retrieval Agent Node] Context Sparse! ({len(retrieved_docs)} docs < threshold {_threshold}). Flagging Web Search Fallback.")
        else:
            print(f"[Retrieval Agent Node] Context Sufficient! ({len(retrieved_docs)} docs).")
        return {"retrieved_docs": retrieved_docs, "need_web_search": need_web_search}

    def _web_search_node(state: ResearchState) -> Dict[str, Any]:
        queries = state.get("search_queries", [state["topic"]])
        print(f"\n[Web Search Fallback Node] Executing live Tavily search...")
        web_results: List[Dict[str, Any]] = []
        tavily_key = _tavily_key
        if TavilySearchResults is not None and tavily_key and not tavily_key.startswith("your_"):
            try:
                tavily = TavilySearchResults(tavily_api_key=tavily_key, max_results=2)
                for q in queries[:2]:
                    results = tavily.invoke({"query": q})
                    if isinstance(results, list):
                        web_results.extend(results)
                print(f"[Web Search Fallback Node] Fetched {len(web_results)} snippets from Tavily.")
            except Exception as e:
                print(f"[Web Search Fallback Node] Tavily error ({e}). Using mock data.")
                web_results = _get_mock_web_results(state["topic"])
        else:
            print("[Web Search Fallback Node] Tavily key missing. Using mock data.")
            web_results = _get_mock_web_results(state["topic"])
        return {"web_search_results": web_results}

    def _synthesis_node(state: ResearchState) -> Dict[str, Any]:
        topic = state["topic"]
        docs = state.get("retrieved_docs", [])
        web_results = state.get("web_search_results", [])
        print(f"\n[Synthesis Agent Node] Compiling final report for: '{topic}'...")
        doc_context_str = ""
        if docs:
            for i, doc in enumerate(docs, 1):
                source = doc.metadata.get("source", "Supabase Vector Store")
                doc_context_str += f"\n--- Vector Document [{i}] (Source: {source}) ---\n{doc.page_content}\n"
        else:
            doc_context_str = "No dense vector documents were retrieved."
        web_context_str = ""
        if web_results:
            for i, res in enumerate(web_results, 1):
                title = res.get("title", "Web Result")
                url = res.get("url", "#")
                snippet = res.get("snippet", res.get("content", ""))
                web_context_str += f"\n--- Web Search Result [{i}] ---\nTitle: {title}\nURL: {url}\nSnippet: {snippet}\n"
        else:
            web_context_str = "No web search fallback context was required."
        llm = get_groq_llm(groq_api_key=_groq_key, temperature=0.2)
        if llm:
            try:
                synthesis_prompt = ChatPromptTemplate.from_messages([
                    ("system", """You are a Lead AI Systems Engineer writing an executive technical report.
Synthesize the provided vector database context and web search context into a highly structured, polished Markdown report.

Required Sections:
# Executive Summary
## Key Technical Insights
## Comparative Analysis & Findings
## Source Citations

Ensure tone is professional, technical, authoritative, and concise."""),
                    ("human", """Research Topic: {topic}

=== SUPABASE VECTOR DATABASE CONTEXT ===
{vector_context}

=== WEB SEARCH FALLBACK CONTEXT ===
{web_context}
""")
                ])
                messages = synthesis_prompt.format_messages(
                    topic=topic,
                    vector_context=doc_context_str,
                    web_context=web_context_str
                )
                response = llm.invoke(messages)
                report_content = response.content
            except Exception as e:
                print(f"[Synthesis Agent Node] Groq LLM synthesis failed ({e}). Generating template report.")
                report_content = _generate_fallback_report(topic, doc_context_str, web_context_str)
        else:
            print("[Synthesis Agent Node] No Groq API Key. Generating offline report.")
            report_content = _generate_fallback_report(topic, doc_context_str, web_context_str)
        print("[Synthesis Agent Node] Report synthesized successfully.")
        return {"final_report": report_content}

    # ── Build & compile the graph ──────────────────────────────────────────────
    builder = StateGraph(ResearchState)
    builder.add_node("orchestrator", _orchestrator_node)
    builder.add_node("retriever",    _retrieval_node)
    builder.add_node("web_search",   _web_search_node)
    builder.add_node("synthesis",    _synthesis_node)

    builder.add_edge(START, "orchestrator")
    builder.add_edge("orchestrator", "retriever")
    builder.add_conditional_edges(
        "retriever",
        decide_fallback,
        {"web_search": "web_search", "synthesis": "synthesis"}
    )
    builder.add_edge("web_search", "synthesis")
    builder.add_edge("synthesis", END)

    graph = builder.compile()
    return graph


